"""Offline assembly; retain stock external-image policy failures truthfully.

The user explicitly requested local processing. Original artwork is therefore
extracted locally instead of regenerated by the skill's external image backend.
Stock validation reports are never changed. Structural failures still block.
"""
import argparse
import hashlib
import json
import posixpath
import re
import sys
import subprocess
from pathlib import Path
from zipfile import ZipFile
from xml.etree import ElementTree as ET
from PIL import Image, ImageChops, ImageFilter, ImageStat

RUNTIME = Path(__file__).resolve().parents[1] / 'cli' / 'editppt' / 'runtime'
sys.path.insert(0, str(RUNTIME))
from build_pptx_from_manifest import write_deck
from _input_normalization import collect_notes_from_pptx, slide_parts_from_pptx

POLICY_REASONS = {
    'foreground visual decisions must not use direct crops, native approximations, emoji/text symbols, or warning-only fallbacks',
    'foreground visual objects require matching asset-sheet-separated or imagegen provenance',
    'foreground asset provenance must use asset-sheet-separated or imagegen',
    'legacy foreground visual objects require an asset-sheet separation decision and matching permitted asset provenance',
}
CHECK_FIELDS = (
    'missing_required_text', 'missing_parts', 'missing_relationship_targets',
    'missing_asset_provenance', 'missing_manifest_images', 'missing_provenance_sources',
    'invalid_asset_provenance', 'media_hash_mismatches', 'media_manifest_mismatch',
    'line_geometry_violations', 'table_structure_violations',
)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--run', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--allow-local-assets', action='store_true',
                    help='Explicit local-source exception policy; use only for an authorized local reconstruction route.')
    ap.add_argument('--notes-from', type=Path, help='Original PPTX when preparation used a PDF intermediate.')
    args = ap.parse_args()
    args.run = args.run.resolve()
    args.out = args.out.resolve()
    if args.out.suffix.lower() != '.pptx':
        raise RuntimeError('Output must be a PPTX path')
    deck = json.loads((args.run/'deck_manifest.json').read_text(encoding='utf-8-sig'))
    pages = deck.get('pages', [])
    if not pages or deck.get('page_count', len(pages)) != len(pages):
        raise RuntimeError('Empty or inconsistent deck page inventory')
    protected = {(args.run/p['page_dir']/'page.pptx').resolve() for p in pages}
    protected.update((args.run/p).resolve() for p in deck.get('inputs', []))
    if args.notes_from:
        protected.add(args.notes_from.resolve())
    if args.out in protected:
        raise RuntimeError('Output would overwrite a source or page artifact')
    audit_dir = args.run/'local-validation'
    audit_dir.mkdir(exist_ok=True)
    entries, checks = [], []
    for n, page in enumerate(pages, start=1):
        directory = (args.run / page['page_dir']).resolve()
        directory.relative_to(args.run)
        required = ['manifest.json', 'imagegen-jobs.json', 'page.pptx', 'preview.png',
                    'split_assets_contact.png', 'validation.json', 'page_result.json']
        missing = [name for name in required if not (directory/name).is_file()]
        if missing:
            raise RuntimeError(f'{directory.name}: missing artifacts {missing}')
        path = directory / 'manifest.json'
        manifest = json.loads(path.read_text(encoding='utf-8-sig'))
        raw_report = audit_dir / f'{directory.name}.stock.json'
        raw_report.unlink(missing_ok=True)
        result = subprocess.run([sys.executable, str(RUNTIME/'validate_pptx.py'),
                                 str(directory/'page.pptx'), '--manifest', str(path),
                                 '--report', str(raw_report)], capture_output=True, text=True,
                                encoding='utf-8', errors='replace')
        if result.returncode not in (0, 1) or not raw_report.is_file():
            raise RuntimeError(f'{directory.name}: validator failed: {result.stderr[-1500:]}')
        report = json.loads(raw_report.read_text(encoding='utf-8-sig'))
        problems = {k:report[k] for k in CHECK_FIELDS if report.get(k)}
        if not report.get('zip_ok') or report.get('slides') != 1:
            problems['package'] = 'Invalid one-slide package'
        if (report.get('required_text') and not report.get('editable_text_shapes')
                and not report.get('editable_table_cells')):
            problems['editability'] = 'Required text has no native editable objects'
        exceptions = []
        for v in report.get('page_contract_violations', []):
            reason = v.get('reason')
            if args.allow_local_assets and reason in POLICY_REASONS and local_asset_exception(v, manifest):
                exceptions.append(v)
            elif args.allow_local_assets and reason == 'full-slide raster background cannot be assembled with editable text':
                asset = directory / v['path']
                original_pixels = unchanged_background(asset, directory/'source.png', manifest)
                if asset.name == 'source.png' or original_pixels:
                    problems.setdefault('contract', []).append(v)
                elif (manifest.get('background_strategy', {}).get('removed_foreground')
                      and manifest.get('background_strategy', {}).get('comparison_note')
                      and manifest.get('quality_checks', {}).get('background_strategy_checked') is True):
                    exceptions.append(v)
                else:
                    problems.setdefault('contract', []).append(v)
            else:
                problems.setdefault('contract', []).append(v)
        if problems:
            raise RuntimeError(f'{directory.name}: {json.dumps(problems,ensure_ascii=False)}')
        entries.append({'manifest':manifest,'manifest_path':str(path),'page_index':n})
        checks.append({'page':n,'structural_checks_passed':True,'stock_skill_passed':report['passed'],
                       'local_only_policy_exceptions':exceptions,
                       'text_shapes':report.get('editable_text_shapes'),
                       'editable_table_cells':report.get('editable_table_cells'),
                       'manifest_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
                       'raw_stock_report':str(raw_report)})
    if args.notes_from:
        with ZipFile(args.notes_from) as z:
            if len(slide_parts_from_pptx(z)) != len(pages):
                raise RuntimeError('Original notes-source slide count does not match prepared deck')
        notes = collect_notes_from_pptx(args.notes_from)
    else:
        notes_path = args.run / deck.get('notes_manifest', 'notes_manifest.json')
        notes = json.loads(notes_path.read_text(encoding='utf-8-sig')).get('notes', [])
    # Preserve note text, not raw XML with unresolved original master/media relationships.
    notes = [{k:v for k,v in note.items() if k != 'notes_xml'} for note in notes]
    candidate = audit_dir/'assembled-candidate.pptx'
    write_deck(deck, entries, candidate, notes)
    ns={'p':'http://schemas.openxmlformats.org/presentationml/2006/main',
        'a':'http://schemas.openxmlformats.org/drawingml/2006/main'}
    with ZipFile(candidate) as z:
        if z.testzip() is not None:
            raise RuntimeError('Final ZIP CRC check failed')
        names = set(z.namelist())
        slides = [n for n in names if re.fullmatch(r'ppt/slides/slide\d+\.xml',n)]
        if len(slides) != len(pages):
            raise RuntimeError('Final slide count mismatch')
        for name in names:
            if name.endswith('.xml') or name.endswith('.rels'):
                root = ET.fromstring(z.read(name))
                if name.endswith('.rels'):
                    base = posixpath.dirname(posixpath.dirname(name))
                    for rel in root:
                        if rel.get('TargetMode') == 'External':
                            continue
                        target = rel.get('Target')
                        resolved = target.lstrip('/') if target.startswith('/') else posixpath.normpath(posixpath.join(base,target))
                        if resolved not in names:
                            raise RuntimeError(f'Missing final relationship target: {name} -> {resolved}')
        for n in range(1,len(pages)+1):
            r=ET.fromstring(z.read(f'ppt/slides/slide{n}.xml'))
            final_text=''.join(x.text or '' for x in r.findall('.//a:t',ns))
            with ZipFile(Path(entries[n-1]['manifest_path']).parent/'page.pptx') as page_zip:
                page_xml=ET.fromstring(page_zip.read('ppt/slides/slide1.xml'))
                page_text=''.join(x.text or '' for x in page_xml.findall('.//a:t',ns))
            if final_text != page_text:
                raise RuntimeError(f'Slide order or editable text mismatch at {n}')
    expected_notes={int(n['page_index']):n['text'] for n in notes if n.get('text')}
    actual_notes={int(n['page_index']):n['text'] for n in collect_notes_from_pptx(candidate)}
    if actual_notes != expected_notes:
        raise RuntimeError('Speaker notes content/page mapping mismatch')
    args.out.parent.mkdir(parents=True, exist_ok=True)
    import shutil
    shutil.copyfile(candidate, args.out)
    output_report={'assembly_processing':'local','local_source_exceptions_enabled':args.allow_local_assets,
                   'structural_checks_passed':True,'notes_content_verified':True,
                   'slide_count':len(pages),'pages':checks,'output':str(args.out),
                   'output_sha256':hashlib.sha256(args.out.read_bytes()).hexdigest()}
    (audit_dir/'local-assembly-validation.json').write_text(json.dumps(output_report,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({'output':str(args.out),'slides':len(pages),'structural_checks_passed':True,
                      'report':str(audit_dir/'local-assembly-validation.json')},ensure_ascii=False))

def local_asset_exception(violation, manifest):
    """Only exact local-source policy conflicts, with a real linked image/provenance."""
    field = violation.get('field', '')
    match = re.fullmatch(r'(visual_inventory|asset_provenance)\[(\d+)\]', field)
    if not match:
        return False
    items = manifest.get(match.group(1), [])
    index = int(match.group(2))
    if index >= len(items) or not isinstance(items[index], dict):
        return False
    item = items[index]
    path = violation.get('path') or item.get('path')
    images = {x.get('path') for x in manifest.get('images', [])}
    provenance = next((x for x in manifest.get('asset_provenance', []) if x.get('path') == path), {})
    return (path in images and provenance.get('source_type') == 'user-provided'
            and bool(provenance.get('provenance_note'))
            and (not item.get('source_type') or item['source_type'] == 'user-provided'))

def unchanged_background(asset, source, manifest):
    """Reject original or nearly identical recompressed/resized source rasters.

This is a conservative duplicate-source gate, not proof of successful inpainting.
Source/clean-base visual comparison remains mandatory.
"""
    with Image.open(asset) as a, Image.open(source) as b:
        b = b.convert('RGB')
        a = a.convert('RGB').resize(b.size, Image.Resampling.LANCZOS)
        diff = ImageChops.difference(a.filter(ImageFilter.GaussianBlur(1)),
                                     b.filter(ImageFilter.GaussianBlur(1)))
        if sum(ImageStat.Stat(diff).mean)/3 < 3:
            return True
        region_differences = []
        for item in manifest.get('text_boxes', []):
            if not item.get('box_px'):
                continue
            x,y,w,h = item['box_px']
            box = (max(0,int(x)), max(0,int(y)), min(b.width,int(x+w)), min(b.height,int(y+h)))
            if box[2] > box[0] and box[3] > box[1]:
                region_differences.append(sum(ImageStat.Stat(diff.crop(box)).mean)/3)
        return bool(region_differences) and max(region_differences) < 5

if __name__ == '__main__':
    main()
